"""Architecture tables, generated from the facade and the managers' #includes.

Regions: ``init-order``, ``manager-map``.
"""

from __future__ import annotations

import hal_extract as hx


def init_order(page) -> str:
    f = hx.facade()
    hdr, cpp = hx.BOARD["facade_header"], hx.BOARD["facade_source"]
    out = [
        f"Generated by `tools/docs/gen.py` from [`{cpp.rsplit('/', 1)[-1]}`]({page.rel(cpp)})\n"
        f"(`{hx.BOARD['facade_class']}::{hx.BOARD['init_function']}`); do not edit.",
        "",
        "| Step | Manager | Member | If it fails |",
        "| ---: | --- | --- | --- |",
    ]
    for i, s in enumerate(f["init"], 1):
        fail = "**initialisation fails** (`EnsureInitialized()` returns false)" if s["required"] else \
            "warning; the system runs degraded"
        out.append(f"| {i} | `{s['class']}` | `{hx.BOARD['facade_class'].lower()}.{s['member']}` | {fail} |")
    return "\n".join(out)


def manager_map(page) -> str:
    d = hx.dependencies()
    out = [
        f"Generated by `tools/docs/gen.py` from the `#include` lines of\n"
        f"[`{hx.BOARD['managers_dir']}`]({page.rel(hx.BOARD['managers_dir'])}) and the hf-core handlers; do not edit.",
        "",
        "| Manager | Uses managers | hf-core handlers (driver) | Drivers used directly | Interface classes |",
        "| --- | --- | --- | --- | --- |",
    ]
    def code(xs):
        return ", ".join(f"`{x}`" for x in xs) or "-"
    for name, m in d["managers"].items():
        handlers = ", ".join(
            f"`{h}` ({', '.join(d['handler_drivers'].get(h, [])) or '-'})" for h in m["handlers"]
        ) or "-"
        hdr = next((f for f in m["files"] if f.endswith(".h")), m["files"][0])
        out.append(f"| [`{name}`]({page.rel(hdr)}) | {code(m['managers'])} | {handlers} | {code(m['drivers'])} | "
                   f"{code(m['interfaces'])} |")
    return "\n".join(out)


REGIONS = {"init-order": init_order, "manager-map": manager_map}
