"""Example catalogue, generated from examples/esp32/app_config.yml and the @brief of each app's source file.

Region: ``examples-catalogue``.
"""

from __future__ import annotations

import hal_extract as hx

#: Families, tried in order: (title, test on the app name). The rules are here so the grouping is reviewable.
FAMILIES = [
    ("Start here", lambda n: n == hx.examples()["metadata"].get("default_app")),
    ("Manager tests", lambda n: n.endswith("_test")),
    ("TMCL parameter tools", lambda n: "tmcl" in n),
    ("Motor benches (motion)", lambda n: "bldc" in n and "telemetry" not in n),
    ("Board bring-up and smoke tests", lambda n: True),
]


def catalogue(page) -> str:
    data = hx.examples()
    rel = hx.BOARD["app_config"]
    apps = data["apps"]
    by_source: dict[str, list[str]] = {}
    for a in apps:
        by_source.setdefault(a["source"], []).append(a["name"])
    out = [
        f"Generated by `tools/docs/gen.py` from [`{rel}`]({page.rel(rel)})\n"
        "and each source file's `@brief`; do not edit.",
        "",
        f"{len(apps)} apps, {sum(a['ci'] for a in apps)} built by CI on every pull request. Target "
        f"`{data['metadata'].get('target', '')}`, ESP-IDF {', '.join(data['metadata'].get('idf_versions', []))}.",
    ]
    placed: set[str] = set()
    for title, test in FAMILIES:
        group = [a for a in apps if a["name"] not in placed and test(a["name"])]
        if not group:
            continue
        placed |= {a["name"] for a in group}
        out += ["", f"### {title}", "", "| App (`APP_TYPE`) | What it does | CI | Source |", "| --- | --- | :---: | --- |"]
        for a in group:
            twins = [n for n in by_source[a["source"]] if n != a["name"]]
            note = f" Shares its source with `{twins[0]}`; selected by `EXAMPLE_TYPE_{a['name']}`." if twins else ""
            brief = (a["brief"] or "").replace("|", "\\|")
            src = a["source"].rsplit("/", 1)[-1]
            out.append(f"| `{a['name']}` | {brief}{note} | {'yes' if a['ci'] else '-'} | [`{src}`]({page.rel(a['source'])}) |")
    return "\n".join(out)


REGIONS = {"examples-catalogue": catalogue}
